import "server-only";
import { and, asc, eq, inArray, ne, notInArray, sql } from "drizzle-orm";
import { db } from "../../../db/dbClient";
import {
  eventsTable,
  hallsTable,
  sessionRegistrationsTable,
  sessionsTable,
  sessionSpeakersTable,
  speakersProfilesTable,
  usersTable,
  type EventSession,
  type SessionSpeaker,
} from "../../../db/schemas";

type SpeakerRole = SessionSpeaker["role"];

/** The columns of a hall the service needs to accept it for a session. */
export type HallRef = {
  id: string;
  venueId: string;
  isActive: boolean;
  /** Seats: also the limit for sessions here that need booking. */
  capacity: number;
};

/** The columns an edit may change. A key that is absent is left alone. */
export type SessionPatch = Partial<{
  title: string;
  type: EventSession["type"];
  mode: EventSession["mode"];
  hallId: string | null;
  onlineUrl: string | null;
  startAt: Date;
  endAt: Date;
  requiresRegistration: boolean;
  price: number;
}>;

export type NewSession = {
  /** Generated by the service: the same id is stored in the Strapi entry's `sessionId`. */
  id: string;
  eventId: string;
  hallId: string | null;
  /** Strapi documentId of the Session Detail created for this session. */
  cmsSessionId: string;
  title: string;
  type: EventSession["type"];
  mode: EventSession["mode"];
  status: EventSession["status"];
  onlineUrl: string | null;
  startAt: Date;
  endAt: Date;
  requiresRegistration: boolean;
  price: number;
  /** speaker_profiles ids, in display order. */
  speakers: { speakerId: string; role: SpeakerRole }[];
};

/** What the Strapi content calls need of a session: its id and the link to its Strapi entry. */
export type SessionRef = Pick<EventSession, "id" | "cmsSessionId">;

/** A session row with its speakers. */
export type SessionWithSpeakers = EventSession & {
  /** The hall's name (halls.name); null for a session with no hall (online). */
  hallName: string | null;
  speakers: {
    /** speaker_profiles.id */
    speakerId: string;
    /** The speaker's full name (from their user), so a screen needs no second lookup. */
    name: string;
    role: SpeakerRole;
    displayOrder: number;
  }[];
};

/**
 * Adds what a screen needs beside each session's own columns: its speakers (in display order,
 * with their names) and its hall's name. Two queries for ALL the sessions, never one per session.
 */
async function withSpeakers(
  rows: EventSession[],
): Promise<SessionWithSpeakers[]> {
  if (rows.length === 0) return [];

  const hallIds = [
    ...new Set(rows.flatMap((row) => (row.hallId ? [row.hallId] : []))),
  ];

  const [speakerRows, hallRows] = await Promise.all([
    db
      .select({
        sessionId: sessionSpeakersTable.sessionId,
        speakerId: sessionSpeakersTable.speakerId,
        role: sessionSpeakersTable.role,
        displayOrder: sessionSpeakersTable.displayOrder,
        firstName: usersTable.firstName,
        lastName: usersTable.lastName,
      })
      .from(sessionSpeakersTable)
      // The name lives on the user the speaker profile belongs to.
      .innerJoin(
        speakersProfilesTable,
        eq(speakersProfilesTable.id, sessionSpeakersTable.speakerId),
      )
      .innerJoin(usersTable, eq(usersTable.id, speakersProfilesTable.userId))
      .where(
        inArray(
          sessionSpeakersTable.sessionId,
          rows.map((row) => row.id),
        ),
      )
      .orderBy(asc(sessionSpeakersTable.displayOrder)),
    hallIds.length === 0
      ? Promise.resolve([])
      : db
          .select({ id: hallsTable.id, name: hallsTable.name })
          .from(hallsTable)
          .where(inArray(hallsTable.id, hallIds)),
  ]);
  const hallNames = new Map(hallRows.map((hall) => [hall.id, hall.name]));

  return rows.map((row) => ({
    ...row,
    hallName: row.hallId ? (hallNames.get(row.hallId) ?? null) : null,
    speakers: speakerRows
      .filter((speaker) => speaker.sessionId === row.id)
      .map(({ speakerId, role, displayOrder, firstName, lastName }) => ({
        speakerId,
        name: `${firstName} ${lastName}`,
        role,
        displayOrder,
      })),
  }));
}

/** One scheduled session of a public event, with what its public page shows beyond the session. */
export type PublicSessionRow = Pick<
  EventSession,
  | "id"
  | "title"
  | "type"
  | "mode"
  | "startAt"
  | "endAt"
  | "price"
  | "requiresRegistration"
> & {
  /** Only to load the Strapi content: the public DTO never carries it. */
  cmsSessionId: string | null;
  hallName: string | null;
  event: {
    slug: string;
    title: string;
    status: "published" | "cancelled";
    timezone: string;
  };
  /** In display order. A suspended speaker is left out: they have no public page. */
  speakers: {
    slug: string;
    firstName: string;
    lastName: string;
    role: SpeakerRole;
  }[];
};

export const sessionRepository = {
  /** Every session of an event, earliest first (one with no time yet comes last). */
  async listSessionsByEvent(eventId: string): Promise<SessionWithSpeakers[]> {
    const rows = await db
      .select()
      .from(sessionsTable)
      .where(eq(sessionsTable.eventId, eventId))
      // id breaks ties, so the order never changes between two calls.
      .orderBy(asc(sessionsTable.startAt), asc(sessionsTable.id));
    return withSpeakers(rows);
  },

  /**
   * One session of THIS event. Both ids are in the query, so a session of another event is
   * "not found", never returned.
   */
  async findSessionInEvent(
    eventId: string,
    sessionId: string,
  ): Promise<SessionWithSpeakers | null> {
    const [row] = await db
      .select()
      .from(sessionsTable)
      .where(
        and(
          eq(sessionsTable.id, sessionId),
          eq(sessionsTable.eventId, eventId),
        ),
      );
    if (!row) return null;
    const [session] = await withSpeakers([row]);
    return session ?? null;
  },

  /**
   * One session for its public page, found by the event's public link and the session's id. Only
   * a SCHEDULED session of a published or cancelled event: a draft event, a draft or cancelled
   * session, an unknown id and a session of another event are all "not found", the same answer.
   */
  async findPublicSession(
    slug: string,
    sessionId: string,
  ): Promise<PublicSessionRow | null> {
    const [row] = await db
      .select({
        id: sessionsTable.id,
        title: sessionsTable.title,
        type: sessionsTable.type,
        mode: sessionsTable.mode,
        startAt: sessionsTable.startAt,
        endAt: sessionsTable.endAt,
        price: sessionsTable.price,
        requiresRegistration: sessionsTable.requiresRegistration,
        cmsSessionId: sessionsTable.cmsSessionId,
        hallName: hallsTable.name,
        eventSlug: eventsTable.slug,
        eventTitle: eventsTable.title,
        eventStatus: eventsTable.status,
        eventTimezone: eventsTable.timezone,
      })
      .from(sessionsTable)
      .innerJoin(eventsTable, eq(eventsTable.id, sessionsTable.eventId))
      .leftJoin(hallsTable, eq(hallsTable.id, sessionsTable.hallId))
      .where(
        and(
          eq(sessionsTable.id, sessionId),
          eq(sessionsTable.status, "scheduled"),
          eq(eventsTable.slug, slug),
          inArray(eventsTable.status, ["published", "cancelled"]),
        ),
      )
      .limit(1);
    if (!row) return null;

    const speakers = await db
      .select({
        slug: speakersProfilesTable.slug,
        firstName: usersTable.firstName,
        lastName: usersTable.lastName,
        role: sessionSpeakersTable.role,
      })
      .from(sessionSpeakersTable)
      .innerJoin(
        speakersProfilesTable,
        eq(speakersProfilesTable.id, sessionSpeakersTable.speakerId),
      )
      .innerJoin(usersTable, eq(usersTable.id, speakersProfilesTable.userId))
      .where(
        and(
          eq(sessionSpeakersTable.sessionId, row.id),
          // A suspended speaker has no public page, so they are not named either.
          ne(usersTable.status, "suspended"),
        ),
      )
      .orderBy(asc(sessionSpeakersTable.displayOrder));

    const { eventSlug, eventTitle, eventStatus, eventTimezone, ...session } =
      row;
    return {
      ...session,
      event: {
        slug: eventSlug,
        title: eventTitle,
        // The query only finds these two; a draft never gets here.
        status: eventStatus === "cancelled" ? "cancelled" : "published",
        timezone: eventTimezone,
      },
      speakers,
    };
  },

  /** Seats booked for this session right now (cancelled bookings do not count). */
  async countActiveBookings(sessionId: string): Promise<number> {
    const [row] = await db
      .select({ n: sql<number>`count(*)::int` })
      .from(sessionRegistrationsTable)
      .where(
        and(
          eq(sessionRegistrationsTable.sessionId, sessionId),
          eq(sessionRegistrationsTable.status, "registered"),
        ),
      );
    return row?.n ?? 0;
  },

  /**
   * Changes only the columns in `patch` (`updated_at` follows by itself) and returns the
   * session with its speakers. null = the session is gone. The service has already checked
   * every rule, so this only writes.
   */
  async updateSession(
    sessionId: string,
    patch: SessionPatch,
  ): Promise<SessionWithSpeakers | null> {
    const [row] = await db
      .update(sessionsTable)
      .set(patch)
      .where(eq(sessionsTable.id, sessionId))
      .returning();
    if (!row) return null;
    const [session] = await withSpeakers([row]);
    return session ?? null;
  },

  /**
   * Replaces the session's whole speaker list in ONE transaction, so it never has half a list:
   * 1. the session row is locked, so two replaces at the same moment take turns;
   * 2. only the speakers who are no longer on the list are deleted;
   * 3. the list is written with an upsert: a new speaker is inserted, one who stays only gets
   *    their role and `display_order` (the array position) updated, so their `created_at`
   *    ("added on") is kept. A delete-everything-then-insert would reset it.
   * null = the session is gone. The answer is read AFTER the commit (with the speakers' names):
   * a read through the normal connection could not see the new rows before it.
   */
  async replaceSessionSpeakers(
    sessionId: string,
    speakers: NewSession["speakers"],
  ): Promise<SessionWithSpeakers | null> {
    const saved = await db.transaction(async (tx) => {
      const [row] = await tx
        .select()
        .from(sessionsTable)
        .where(eq(sessionsTable.id, sessionId))
        .for("update");
      if (!row) return null;

      // The list is never empty (the schema needs at least one speaker).
      await tx.delete(sessionSpeakersTable).where(
        and(
          eq(sessionSpeakersTable.sessionId, sessionId),
          notInArray(
            sessionSpeakersTable.speakerId,
            speakers.map((speaker) => speaker.speakerId),
          ),
        ),
      );

      await tx
        .insert(sessionSpeakersTable)
        .values(
          speakers.map((speaker, index) => ({
            sessionId,
            speakerId: speaker.speakerId,
            role: speaker.role,
            displayOrder: index,
          })),
        )
        .onConflictDoUpdate({
          target: [
            sessionSpeakersTable.sessionId,
            sessionSpeakersTable.speakerId,
          ],
          set: {
            role: sql`excluded.role`,
            displayOrder: sql`excluded.display_order`,
          },
        });

      return row;
    });
    if (!saved) return null;

    const [session] = await withSpeakers([saved]);
    return session ?? null;
  },

  /**
   * Cancels the session AND the seats booked for it, in one transaction: either both happen or
   * neither, so no attendee keeps a seat at a cancelled session. The hall is free again at once,
   * because a session holds its hall only while it is not cancelled. null = it was already
   * cancelled (or is gone): the update only touches a session that is not cancelled yet, so two
   * cancels at the same moment cannot both win.
   */
  async cancelSession(
    sessionId: string,
    at: Date,
  ): Promise<SessionWithSpeakers | null> {
    return db.transaction(async (tx) => {
      const [row] = await tx
        .update(sessionsTable)
        .set({ status: "cancelled", cancelledAt: at })
        .where(
          and(
            eq(sessionsTable.id, sessionId),
            ne(sessionsTable.status, "cancelled"),
          ),
        )
        .returning();
      if (!row) return null;

      await tx
        .update(sessionRegistrationsTable)
        .set({ status: "cancelled", cancelledAt: at })
        .where(
          and(
            eq(sessionRegistrationsTable.sessionId, sessionId),
            eq(sessionRegistrationsTable.status, "registered"),
          ),
        );

      const [session] = await withSpeakers([row]);
      return session ?? null;
    });
  },

  /** Links the session to a (new) Strapi entry, when the old link was missing or the entry was deleted. */
  async setCmsSessionId(sessionId: string, documentId: string): Promise<void> {
    await db
      .update(sessionsTable)
      .set({ cmsSessionId: documentId })
      .where(eq(sessionsTable.id, sessionId));
  },

  async findHall(hallId: string): Promise<HallRef | null> {
    const [hall] = await db
      .select({
        id: hallsTable.id,
        venueId: hallsTable.venueId,
        isActive: hallsTable.isActive,
        capacity: hallsTable.capacity,
      })
      .from(hallsTable)
      .where(eq(hallsTable.id, hallId));
    return hall ?? null;
  },

  /** Which of these ids are real speaker PROFILES (one query for the whole list). */
  async findExistingSpeakerIds(speakerIds: string[]): Promise<string[]> {
    if (speakerIds.length === 0) return [];
    const rows = await db
      .select({ id: speakersProfilesTable.id })
      .from(speakersProfilesTable)
      .where(inArray(speakersProfilesTable.id, speakerIds));
    return rows.map((row) => row.id);
  },

  /**
   * Inserts the session and its speakers in ONE transaction: either both are saved or neither,
   * so a session never exists without its speakers. `display_order` is the array position.
   */
  async createSession(input: NewSession): Promise<SessionWithSpeakers> {
    const { speakers, ...columns } = input;

    const saved = await db.transaction(async (tx) => {
      const [session] = await tx
        .insert(sessionsTable)
        .values(columns)
        .returning();
      if (!session) throw new Error("sessions insert returned no row");

      await tx.insert(sessionSpeakersTable).values(
        speakers.map((speaker, index) => ({
          sessionId: session.id,
          speakerId: speaker.speakerId,
          role: speaker.role,
          displayOrder: index,
        })),
      );
      return session;
    });

    // Read after the commit, with the speakers' names and the hall's name.
    const [session] = await withSpeakers([saved]);
    if (!session) throw new Error("sessions insert could not be read back");
    return session;
  },
};

export type SessionRepository = typeof sessionRepository;
